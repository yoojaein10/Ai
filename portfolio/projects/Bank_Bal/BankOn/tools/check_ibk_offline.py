def norm(t):
    return (t or "").replace(",", "").replace(" ", "").strip()


def build(cfg, doc: str):
    gam = process_gam(cfg.gamexport_exe, str(VK.fetch_gam_local(cfg, doc)), str(Path("output") / doc))
    ctx = vf.build_context(cfg, doc, gam.tables, vf.sections_from_gam(gam))
    return ibk.build_ibk(ctx)


def main() -> int:
    cfg = load_config()
    total_ok = total_bad = 0
    for doc, expect in EXPECT.items():
        header, objects = build(cfg, doc)
        print(f"\n===== {doc} — 물건 {len(objects)}개 {[o['_kind'] for o in objects]} =====")
        for (where, label), want in expect.items():
            if where == "헤더":
                got = header.get(label)
            else:
                got = objects[where - 1].get(label) if where - 1 < len(objects) else "<물건 없음>"
            ok = norm(got) == norm(want)
            total_ok += ok
            total_bad += not ok
            print(f"  {'✅' if ok else '❌'} {str(where):4} {label:18} 우리={str(got)[:24]:26} 기대={want}")
    print(f"\n[합계] ✅{total_ok} / ❌{total_bad}")
    return 1 if total_bad else 0


