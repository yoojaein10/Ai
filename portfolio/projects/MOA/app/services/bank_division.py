"""거래처명 → 아마란스 은행구분(관리항목 M1, api11A10의 usermTy1).

코드표는 재무팀이 준 bankcode.png 기준이다(2026-08-05). 주석도 함께 반영:
  - 050 외환: 안 씀
  - 110 농협중: 지역 조합(단위농협·축협·원예·인삼 등). 주석의 "축협,
    민물장어양식수협"에 따라 축협은 160이 아니라 110으로 보낸다(사용자 확정).
  - 120 농협회: 농협은행 ○○지점
  - 850 상호저축은행: 한투 외 저축은행 / 860: 한국투자저축
은행이 아닌 의뢰처(공사·법원·지자체·개인 등)는 880 기타로 본다(사용자 확정).

실측(2026-05~08 매출 라인 8,357건): 은행 판정 59.7%, 나머지는 비은행 의뢰처.
"""

import re

MISC_CODE = "880"  # 기타

# 순서가 곧 우선순위 — 좁은 패턴을 먼저 둔다
# (예: '농협은행'은 120, 그 밖의 '농업협동조합'은 110)
_RULES: "list[tuple[str, str]]" = [
    (r"산림조합", "870"),
    (r"새마을금고|MG새마을", "840"),
    (r"우체국", "710"),
    (r"한국투자저축", "860"),
    (r"저축은행", "850"),
    (r"신협|신용협동조합", "048"),
    (r"축협|축산업협동조합", "110"),
    (r"수협|수산업협동조합", "070"),
    (r"농협은행", "120"),
    (r"농협|농업협동조합|원예농협|인삼농협", "110"),
    (r"국민은행|KB국민", "040"),
    (r"기업은행|중소기업은행|IBK", "030"),
    (r"산업은행|KDB", "020"),
    (r"신한은행|신한금융|^신한", "260"),
    (r"조흥은행", "210"),
    (r"제일은행|SC제일|스탠다드차타드", "230"),
    (r"우리은행|^우리", "200"),
    (r"하나은행|KEB하나|^하나", "810"),
    (r"대구은행|iM뱅크", "310"),
    (r"부산은행", "320"),
    (r"광주은행", "340"),
    (r"제주은행", "350"),
    (r"전북은행", "370"),
    (r"강원은행", "380"),
    (r"경남은행", "390"),
    (r"씨티은행|시티은행", "530"),
]

_COMPILED = [(re.compile(pattern), code) for pattern, code in _RULES]


def bank_division(partner_name: str | None) -> str:
    """거래처명에서 은행구분 코드를 정한다. 은행이 아니면 880(기타)."""
    name = (partner_name or "").replace(" ", "")
    if not name:
        return MISC_CODE
    for pattern, code in _COMPILED:
        if pattern.search(name):
            return code
    return MISC_CODE
