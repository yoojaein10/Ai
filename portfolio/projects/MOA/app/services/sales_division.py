"""감정서번호 → 아마란스 매출구분(관리항목 L2, api11A10의 userlTy2).

재무팀이 준 표(2026-08-05) 기준. 감정서번호 세 번째 자리가 곧 구분이다.
  01-2608-1-XXXX → 01 보상부문      01-2608-2-XXXX → 02 경매부문
  01-2608-3-XXXX → 03 담보부문      01-2608-4-XXXX → 04 일반거래부문
  01-2608-5-XXXX → 05 컨설팅부문    01-2608-6-XXXX → 09 약식부분
  01-2608-7-XXXX → 07 기타(실비)    01-2608-8-XXXX → 06 공시업무(약식 아님)
표에 없던 'A'는 04 일반거래부문으로 한다(사용자 확정 2026-08-05).

최근 1년 실데이터로 대조했을 때 자리별 목적이 표와 맞는다
(3=제1금융권·새마을금고 담보, 2=법원경매, 6=공동주택가격자문, 8=표준지공시지가).

아직 못 정한 자리(B·9·0·'-', 최근 1년 530건)는 None을 돌려주고 전표에
매출구분을 싣지 않는다 — 틀린 구분으로 보내는 것보다 비워두는 게 낫다.
"""

# 국민 약식(400 접수번호)은 감정서번호 체계가 아니라 별도로 09 고정
YAK_SALES_DIVISION = "09"

_BY_SEGMENT = {
    "1": "01",  # 보상부문
    "2": "02",  # 경매부문
    "3": "03",  # 담보부문
    "4": "04",  # 일반거래부문
    "5": "05",  # 컨설팅부문
    "6": "09",  # 약식부분
    "7": "07",  # 기타(실비)
    "8": "06",  # 공시업무
    "A": "04",  # 표에 없던 자리 — 일반거래부문 (사용자 확정)
}


def _type_segment(doc_id: "str | None") -> "str | None":
    """감정서번호에서 유형 자리를 뽑는다 — 두 형식을 안다.

    표준: 01-2603-1-0109 (유형 = 세 번째 조각).
    가지번호(분할 청구): 012603-1-0109-1 / 012607-4-023621 — 사무소+년월이
    붙어 첫 조각이 6자리이고 유형이 두 번째 조각이다 (2026-08-13 실증:
    012603-1-0109-1 기본전표가 매출구분 없이 나가 아마란스 발행 검증 오류).
    """
    parts = str(doc_id or "").strip().split("-")
    if len(parts) >= 3 and len(parts[0]) == 6 and parts[0].isdigit():
        return parts[1] or None
    if len(parts) >= 4:
        return parts[2] or None
    return None


def sales_division(doc_id: str | None) -> "str | None":
    """감정서번호의 유형 자리로 매출구분을 정한다."""
    segment = _type_segment(doc_id)
    return _BY_SEGMENT.get(segment.upper()) if segment else None


def sales_account(doc_id: str | None) -> str:
    """감정서 유형별 매출 계정과목 — 재무팀 지침(2026-08-06).

    약식(유형 자리 '6')은 기타수수료 4010002, 나머지는 감정수수료 4010001.
    """
    return "4010002" if _type_segment(doc_id) == "6" else "4010001"
